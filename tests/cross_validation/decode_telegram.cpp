int main() {
    constexpr int START_ADDRESS = 0x13;
    int packet_size = mbus_data[1] + 6;

    MBusinoLib payload(254);
    JsonDocument jsonBuffer;
    JsonArray root = jsonBuffer.add<JsonArray>();
    uint8_t fields = payload.decode(
        &mbus_data[START_ADDRESS],
        packet_size - START_ADDRESS - 2,
        root
    );

    /* Serialise the entire JsonArray to stdout */
    serializeJson(root, std::cout);
    std::cout << std::endl;

    return (payload.getError() != 0) ? 1 : 0;
}
